using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace AwithGameFrame.Tools.Configuration
{
    /// <summary>Generates HTTP DTOs/endpoints from a wire contract and checks conservative JSON compatibility.</summary>
    public static class ProtocolCompiler
    {
        private static readonly Regex Identifier = new Regex("^[A-Z][a-zA-Z0-9_]*\\z", RegexOptions.CultureInvariant);
        private static readonly HashSet<string> Types = new HashSet<string> { "int", "long", "bool", "double", "string" };

        public static string Compile(string schemaJson, string baselineJson = null)
        {
            using var schema = JsonDocument.Parse(schemaJson);
            var root = schema.RootElement;
            Validate(root);
            if (baselineJson != null)
            {
                using var baseline = JsonDocument.Parse(baselineJson);
                Validate(baseline.RootElement);
                CheckCompatibility(baseline.RootElement, root);
            }
            var ns = root.GetProperty("namespace").GetString();
            var endpoints = root.GetProperty("endpoints").EnumerateArray().OrderBy(e => e.GetProperty("name").GetString(), StringComparer.Ordinal).ToArray();
            var code = new StringBuilder("// <auto-generated />\nusing System.Net.Http;\nusing System.Runtime.Serialization;\nusing AwithGameFrame.Networking;\n\nnamespace ").Append(ns).Append("\n{\n");
            foreach (var endpoint in endpoints)
            {
                var name = endpoint.GetProperty("name").GetString();
                foreach (var side in new[] { "request", "response" })
                {
                    code.Append("    [DataContract]\n    public sealed class ").Append(name).Append(side == "request" ? "Request" : "Response").Append("\n    {\n");
                    foreach (var field in endpoint.GetProperty(side).EnumerateArray())
                    {
                        code.Append("        [DataMember(Name = ").Append(JsonSerializer.Serialize(field.GetProperty("wireName").GetString())).Append(", IsRequired = ").Append(Required(field) ? "true" : "false").Append(")]\n        public ").Append(field.GetProperty("type").GetString()).Append(' ').Append(field.GetProperty("name").GetString()).Append(" { get; set; }\n");
                    }
                    code.Append("    }\n\n");
                }
            }
            code.Append("    public static class GameProtocol\n    {\n        public const int Version = ").Append(root.GetProperty("version").GetInt32()).Append(";\n");
            foreach (var endpoint in endpoints)
            {
                var name = endpoint.GetProperty("name").GetString();
                var method = endpoint.GetProperty("method").GetString();
                code.Append("        public static readonly ProtocolEndpoint<").Append(name).Append("Request, ").Append(name).Append("Response> ").Append(name).Append(" = new ProtocolEndpoint<").Append(name).Append("Request, ").Append(name).Append("Response>(new HttpMethod(").Append(JsonSerializer.Serialize(method)).Append("), ").Append(JsonSerializer.Serialize(endpoint.GetProperty("path").GetString())).Append(", ").Append(method == "GET" || method == "DELETE" ? "false" : "true").Append(");\n");
            }
            return code.Append("    }\n}\n").ToString();
        }

        private static bool Required(JsonElement field) => !field.TryGetProperty("required", out var value) || value.GetBoolean();

        private static void Validate(JsonElement root)
        {
            var ns = root.GetProperty("namespace").GetString();
            if (string.IsNullOrWhiteSpace(ns) || ns.Split('.').Any(p => !Identifier.IsMatch(p)) || root.GetProperty("version").GetInt32() < 1)
                throw new InvalidDataException("Invalid protocol namespace or version.");
            var names = new HashSet<string>(StringComparer.Ordinal) { "GameProtocol", "Version" };
            var types = new HashSet<string>(StringComparer.Ordinal) { "GameProtocol" };
            foreach (var endpoint in root.GetProperty("endpoints").EnumerateArray())
            {
                var name = endpoint.GetProperty("name").GetString();
                var method = endpoint.GetProperty("method").GetString();
                var path = endpoint.GetProperty("path").GetString();
                if (name == null || !Identifier.IsMatch(name) || !names.Add(name) || !types.Add(name + "Request") || !types.Add(name + "Response"))
                    throw new InvalidDataException("Invalid or duplicate endpoint name.");
                if (!new[] { "GET", "POST", "PUT", "PATCH", "DELETE" }.Contains(method) || string.IsNullOrWhiteSpace(path) ||
                    path.StartsWith("/") || path.Contains("..") || path.Contains(":") || path.Contains("\\") || path.Contains("#") || path.Any(char.IsControl))
                    throw new InvalidDataException("Invalid endpoint method/path: " + name);
                foreach (var side in new[] { "request", "response" })
                {
                    var fields = new HashSet<string>(StringComparer.Ordinal);
                    var wires = new HashSet<string>(StringComparer.Ordinal);
                    foreach (var field in endpoint.GetProperty(side).EnumerateArray())
                    {
                        var fieldName = field.GetProperty("name").GetString();
                        var wire = field.GetProperty("wireName").GetString();
                        if (fieldName == null || !Identifier.IsMatch(fieldName) || fieldName == name + (side == "request" ? "Request" : "Response") || !fields.Add(fieldName) ||
                            string.IsNullOrWhiteSpace(wire) || !Regex.IsMatch(wire, "^[a-zA-Z][a-zA-Z0-9_]*\\z") || !wires.Add(wire) || !Types.Contains(field.GetProperty("type").GetString()))
                            throw new InvalidDataException("Invalid field in " + name + "." + side);
                        _ = Required(field);
                    }
                    if ((method == "GET" || method == "DELETE") && side == "request" && fields.Count != 0)
                        throw new InvalidDataException("GET/DELETE query parameters require an explicit transport binding; this generator only emits empty request DTOs for them.");
                }
            }
        }

        private static void CheckCompatibility(JsonElement before, JsonElement after)
        {
            if (after.GetProperty("version").GetInt32() < before.GetProperty("version").GetInt32()) throw new InvalidDataException("Protocol version cannot decrease.");
            var current = after.GetProperty("endpoints").EnumerateArray().ToDictionary(e => e.GetProperty("name").GetString());
            foreach (var oldEndpoint in before.GetProperty("endpoints").EnumerateArray())
            {
                var name = oldEndpoint.GetProperty("name").GetString();
                if (!current.TryGetValue(name, out var next) || next.GetProperty("method").GetString() != oldEndpoint.GetProperty("method").GetString() || next.GetProperty("path").GetString() != oldEndpoint.GetProperty("path").GetString())
                    throw new InvalidDataException("Breaking endpoint change: " + name);
                foreach (var side in new[] { "request", "response" })
                {
                    var oldFields = oldEndpoint.GetProperty(side).EnumerateArray().ToDictionary(f => f.GetProperty("wireName").GetString());
                    var newFields = next.GetProperty(side).EnumerateArray().ToDictionary(f => f.GetProperty("wireName").GetString());
                    foreach (var field in oldFields)
                        if (!newFields.TryGetValue(field.Key, out var newField) || newField.GetProperty("type").GetString() != field.Value.GetProperty("type").GetString() || Required(newField) != Required(field.Value))
                            throw new InvalidDataException("Breaking field change: " + name + "." + side + "." + field.Key);
                    foreach (var field in newFields)
                        if (!oldFields.ContainsKey(field.Key) && Required(field.Value)) throw new InvalidDataException("New fields must be optional for rolling compatibility: " + field.Key);
                }
            }
        }
    }
}
